import Combine
import AppKit

/// Session-only, explicitly enabled text history. Never persisted.
@MainActor
final class ClipboardStore: ObservableObject {
    @Published private(set) var items: [String] = []
    @Published private(set) var enabled = false
    @Published private(set) var feedback = ""
    private var lastCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    private static let privateTypes = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    func setEnabled(_ value: Bool) {
        timer?.invalidate(); timer = nil
        enabled = value
        lastCount = NSPasteboard.general.changeCount
        if value {
            timer = Timer.scheduledTimer(withTimeInterval: 0.7, repeats: true) { [weak self] _ in
                Task { @MainActor [weak self] in self?.poll() }
            }
        }
    }

    private func poll() {
        guard enabled else { return }
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: Self.privateTypes),
              let text = pb.string(forType: .string), !text.isEmpty,
              text.utf8.count <= 100_000 else { return }
        items.removeAll { $0 == text }
        items.insert(text, at: 0)
        items = Array(items.prefix(50))
    }

    func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        feedback = pb.setString(text, forType: .string) ? "Copied to clipboard" : "Could not copy"
        lastCount = pb.changeCount
    }

    func remove(_ text: String) { items.removeAll { $0 == text } }
    func clear() { items = []; feedback = "History cleared. The system clipboard is unchanged." }
}
